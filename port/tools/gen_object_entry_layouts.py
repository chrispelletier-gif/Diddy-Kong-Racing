#!/usr/bin/env python3
"""
Generates port/src/game/object_entry_layouts.c from include/level_object_entries.h.

Level object map entries are big endian structs whose layout depends on the object's behaviour.
The generated table lists, for every behaviour id, the offsets of the 16 and 32 bit fields so the
port can byte swap each entry as an object map is loaded.

Behaviour ids map to entry structs through "default-object-entries-order" in
tools/dkr_assets_tool_extract.json, exactly like the asset tool does.
"""
import json, os, re, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
SIZES = {"u8": 1, "s8": 1, "char": 1, "u16": 2, "s16": 2, "u32": 4, "s32": 4, "f32": 4}

def parse_structs(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    text = re.sub(r"Hint\(\(.*?\)\)", "", text)
    structs = {}
    for m in re.finditer(r"typedef struct (\w+)\s*\{(.*?)\}\s*(\w+)\s*;", text, flags=re.S):
        name, body = m.group(3), m.group(2)
        if "union" in body:
            continue
        members = []
        for decl in body.split(";"):
            decl = decl.strip()
            if not decl:
                continue
            tm = re.match(r"(\w+)\s+(.*)", decl)
            typ, names = tm.group(1), tm.group(2)
            for n in names.split(","):
                n = n.strip()
                am = re.match(r"(\w+)\s*(?:\[(.*?)\])?", n)
                count = int(am.group(2), 0) if am.group(2) else 1
                members.append((typ, count))
        structs[name] = members
    return structs

def layout(structs, name, base=0, out=None, align_out=None):
    """Returns (size, alignment) and appends (offset, size) of every 2/4 byte scalar to out."""
    off = 0
    max_align = 1
    for typ, count in structs[name]:
        if typ in SIZES:
            sz = SIZES[typ]
            al = sz
            if off % al:
                off += al - off % al
            for i in range(count):
                if sz > 1 and out is not None:
                    out.append((base + off + i * sz, sz))
            off += sz * count
        else:
            sub_size, al = layout(structs, typ)
            if off % al:
                off += al - off % al
            for i in range(count):
                layout(structs, typ, base + off + i * sub_size, out)
            off += sub_size * count
        max_align = max(max_align, al)
    if off % max_align:
        off += max_align - off % max_align
    return off, max_align

def main():
    text = open(os.path.join(ROOT, "include", "level_object_entries.h")).read()
    structs = parse_structs(text)
    cfg = json.load(open(os.path.join(ROOT, "tools", "dkr_assets_tool_extract.json")))
    order = cfg["misc"]["default-object-entries-order"]
    lines = [
        "/* This file is generated by port/tools/gen_object_entry_layouts.py. Do not edit it by hand. */",
        '#include "types.h"',
        '#include "port_object_entries.h"',
        "",
        "/* For each object behaviour, the size of the entry struct and the offsets of its 16 and 32 bit fields. */",
        "const ObjectEntryLayout gObjectEntryLayouts[128] = {",
    ]
    for behaviour, sname in enumerate(order[:128]):
        fields = []
        size, _ = layout(structs, sname, 0, fields)
        f16 = [o for o, s in fields if s == 2]
        f32 = [o for o, s in fields if s == 4]
        assert len(f16) <= 16 and len(f32) <= 8, sname
        a16 = ", ".join(str(o) for o in f16) or "0"
        a32 = ", ".join(str(o) for o in f32) or "0"
        lines.append("    /* %3d %s */ { %d, %d, %d, { %s }, { %s } }," % (behaviour, sname, size, len(f16), len(f32), a16, a32))
    lines += ["};", ""]
    out = os.path.join(ROOT, "port", "src", "game", "object_entry_layouts.c")
    open(out, "w").write("\n".join(lines))
    print("wrote", out)

if __name__ == "__main__":
    main()
